/* ---------- normalize: schema v2 only, loud on anything else ---------- */
function normalize(raw){
  if (!raw || raw.meta?.schema_version !== 2 || !Array.isArray(raw.trunks) || !raw.trunks.length)
    throw new Error("career.json is not schema_version 2 — run tools/career-map-gen/gen.py build");
  const out = { meta: raw.meta, map: raw.map||{}, ui: raw.ui||{}, identity: raw.identity||null,
                trunks: [], throughlines: [], claims: raw.claims||[], decisions: raw.decisions||[],
                chronology: raw.chronology||[] };
  const ids = new Set();
  raw.trunks.forEach((t,ti)=>{
    const nt = { id: String(t.id), name: t.name, trigger: t.trigger||"", color: t.color||"ink", pos: goodPos(t.pos), threads: [] };
    (t.threads||[]).forEach((th,i)=>{
      if (ids.has(th.id)) throw new Error("duplicate node id "+th.id);
      ids.add(th.id);
      nt.threads.push({ id: String(th.id), name: th.name, years: th.years||"", years_full: th.years_full||th.years||"", trigger: th.trigger||"", detail: th.detail||"",
        plain_line: th.plain_line||"", kind: th.kind||"", employer: th.employer||"", start: th.start||"", end: th.end ?? null,
        pos: goodPos(th.pos), shape: (i % CAPS.length), question_types: th.question_types||[], keywords: th.keywords||[] });
    });
    out.trunks.push(nt);
  });
  (raw.throughlines||[]).forEach((tl,i)=>{
    const nodeIds = (tl.nodeIds||[]).map(String);
    const missing = nodeIds.filter(n => !ids.has(n));
    if (missing.length) throw new Error(`throughline ${tl.id} references unknown node(s): ${missing.join(", ")}`);
    out.throughlines.push({ id: String(tl.id), name: tl.name, trigger: tl.trigger||"", color: tl.color||"ink", nodeIds, plain_reading: tl.plain_reading||"" });
  });
  out.claims.forEach(c => { c.evidence = (c.evidence||[]).filter(e => ids.has(e.node_id)); });
  return out;
}
function goodPos(p){ return (Array.isArray(p)&&p.length===2&&isFinite(p[0])&&isFinite(p[1])) ? p : null; }
const isFrac = (p)=>p[0]>=0&&p[0]<=1&&p[1]>=0&&p[1]<=1;

