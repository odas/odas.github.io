/* ---------- keyboard ---------- */
function setFocus(i){
  if(i<0||i>=FLAT.length)return; focusIdx=i;
  document.querySelectorAll(".node.focused").forEach(n=>n.classList.remove("focused"));
  const g=document.querySelector(`.node[data-id="${FLAT[i]}"]`); if(g){ g.classList.add("focused"); if(VIEW==="map") g.focus({preventScroll:true}); }
}
document.addEventListener("keydown",e=>{
  if(e.target.tagName==="INPUT"||e.target.tagName==="TEXTAREA"||!DATA)return;
  if(e.key==="Escape"){ panel.classList.remove("open"); qindex.classList.remove("open"); clearLight(); return; }
  const key=e.key.toLowerCase();
  if(key==="q"){ if(qindex.classList.contains("open")) qindex.classList.remove("open"); else openQ(); return; }
  if(key==="p"){ panel.classList.remove("open"); setView(VIEW==="map"?"plain":"map", true); return; }
  if(VIEW!=="map") return;
  if(/^[1-9]$/.test(e.key)){ const t=DATA.trunks[Number(e.key)-1]; if(t){ setFocus(FLAT.indexOf(t.id)); openFor(t.id); } return; }
  if(e.key==="ArrowRight"){ e.preventDefault(); setFocus(Math.min(FLAT.length-1,focusIdx+1)); }
  if(e.key==="ArrowLeft"){ e.preventDefault(); setFocus(Math.max(0,focusIdx-1)); }
  if(e.key==="Enter"){ if(focusIdx<0) setFocus(0); openFor(FLAT[focusIdx]); }
});

