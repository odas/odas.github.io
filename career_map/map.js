const LANDSCAPE_ANCHORS=[[0.24,0.30],[0.22,0.70],[0.52,0.80],[0.80,0.64],[0.76,0.24],[0.50,0.18],[0.50,0.50],[0.05,0.5],[0.95,0.5]];
