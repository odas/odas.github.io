function render(data){
  DATA=data; updateMode(); computePositions(data);
  const svg=$("map"); svg.innerHTML="";
  svg.setAttribute("viewBox",`0 0 ${VB.w} ${VB.h}`); svg.setAttribute("preserveAspectRatio","xMidYMid meet");
  const defs=el("defs",{},svg);
  const mkGlow=(id,dev)=>{ const f=el("filter",{id,x:"-150%",y:"-150%",width:"400%",height:"400%"},defs);
    el("feGaussianBlur",{stdDeviation:dev,result:"b"},f); const m=el("feMerge",{},f); el("feMergeNode",{in:"b"},m); el("feMergeNode",{in:"SourceGraphic"},m); };
  mkGlow("glowT",4);
  const gAmbient=el("g",{},svg), gLines=el("g",{},svg), gThrough=el("g",{},svg), gNodes=el("g",{},svg);

  // substrate photo: dark scheme only (light is paper)
  const stage=$("stage");
  const dark = document.documentElement.dataset.scheme==="dark" ||
               (document.documentElement.dataset.scheme!=="light" && window.matchMedia("(prefers-color-scheme: dark)").matches);
  if(dark && data.map.backgroundImageDark){
    stage.classList.add("photo");
    stage.style.backgroundImage=`linear-gradient(rgba(22,24,27,.84), rgba(22,24,27,.9)), url("${encodeURI(data.map.backgroundImageDark)}")`;
  } else { stage.classList.remove("photo"); stage.style.backgroundImage=""; }

  SPORES.forEach(p=>el("circle",{cx:p.x,cy:p.y,r:1.6*SCALE,class:"spore"},gAmbient));
  FLAT=[];
  if(ORIGIN){
    data.trunks.forEach(t=>{ const tp=POS[t.id];
      const pth=el("path",{d:curve(ORIGIN.x,ORIGIN.y,tp.x,tp.y,46),class:"origin-hypha","stroke-width":2.2*SCALE},gLines);
      pth.style.color=cssColor(t.color); });
    el("circle",{cx:ORIGIN.x,cy:ORIGIN.y,r:9*SCALE,class:"origin-dot","stroke-width":1},gAmbient);
  }
  data.trunks.forEach((t,ti)=>{
    const tp=POS[t.id];
    t.threads.forEach(th=>{ const p=POS[th.id];
      const h=el("path",{d:curve(tp.x,tp.y,p.x,p.y,22+((ti*31)%26)),class:"hypha","stroke-width":1.6},gLines); h.style.color=cssColor(t.color); });
    drawNode(gNodes,defs,{id:t.id,label:t.name,years:"",color:t.color,shape:3,r:24,kind:"trunk",glow:true,seed:ti*7+3});
    FLAT.push(t.id);
    t.threads.forEach((th,i)=>{ drawNode(gNodes,defs,{id:th.id,label:th.name,years:th.years,color:t.color,shape:th.shape,r:12,kind:"thread",seed:ti*13+i*5+1}); FLAT.push(th.id); });
  });
  let drawn=0;
  data.throughlines.forEach((tl,i)=>{
    const pts=tl.nodeIds.map(id=>POS[id]).filter(Boolean);
    if(pts.length<2) return;
    let d=`M ${pts[0].x} ${pts[0].y}`;
    for(let k=1;k<pts.length;k++){ const a=pts[k-1],b=pts[k]; d+=` Q ${(a.x+b.x)/2+((i%2?1:-1)*40)} ${(a.y+b.y)/2+40} ${b.x} ${b.y}`; }
    const p=el("path",{d,class:"throughline"+(isDashed(tl.color)?" dashed":""),"data-tl":i,"stroke-width":1.3},gThrough);
    p.style.color=cssColor(tl.color); drawn++;
  });
  svg.dataset.drawn=`${drawn}/${data.throughlines.length}`;
  if(drawn!==data.throughlines.length) badge(`only ${drawn} of ${data.throughlines.length} throughlines could be drawn`);

  buildLegend();
  svg.onclick=(e)=>{ if(e.target.closest(".node"))return; panel.classList.remove("open"); qindex.classList.remove("open"); clearLight(); };
}

function drawNode(parent,defs,o){
  const p=POS[o.id], R=o.r*SCALE;
  const g=el("g",{class:"node",transform:`translate(${p.x},${p.y})`,tabindex:"0",role:"button","aria-label":o.label,"data-id":o.id},parent);
  g.style.color=cssColor(o.color);
  el("rect",{x:-2.2*SCALE,y:-2,width:4.4*SCALE,height:R*0.85,rx:2*SCALE,class:"stem"},g);
  const capD=CAPS[o.shape%CAPS.length](R);
  const cap=el("path",{d:capD,class:"cap","fill-opacity":0.92,transform:`translate(0,${-R*0.15})`},g);
  if(o.glow) cap.setAttribute("filter","url(#glowT)");
  const clipId="clip-"+safeId(o.id); const cp=el("clipPath",{id:clipId},defs); el("path",{d:capD,transform:`translate(0,${-R*0.15})`},cp);
  const gs=el("g",{"clip-path":`url(#${clipId})`},g);
  const n=2+(o.seed%3);
  for(let k=0;k<n;k++){ const sx=(((o.seed*67+k*41)%100)/100-0.5)*R*1.3, sy=-R*(0.35+(((o.seed*29+k*53)%50))/100);
    el("ellipse",{cx:sx,cy:sy,rx:R*0.11,ry:R*0.08,class:"cap-spot"},gs); }
  el("circle",{class:"ring",r:R+9*SCALE},g);
  const fs=(o.kind==="thread"?12*SCALE:14*SCALE);
  el("text",{class:"nlabel",y:R+16*SCALE,"font-size":fs},g).textContent=o.label;
  if(o.years) el("text",{class:"nyears",y:R+29*SCALE,"font-size":10*SCALE},g).textContent=o.years;
  g.addEventListener("click",()=>{ setFocus(FLAT.indexOf(o.id)); openFor(o.id); });
  g.addEventListener("keydown",e=>{ if(e.key==="Enter"||e.key===" "){e.preventDefault();openFor(o.id);} });
}

