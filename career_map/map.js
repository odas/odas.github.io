let POS={}, ORIGIN=null, SPORES=[];
function computePositions(data){
  POS={}; ORIGIN=null; SPORES=[];
  const abs=[]; const collect=p=>{ if(p&&!isFrac(p)) abs.push(p); };
  data.trunks.forEach(t=>{ collect(t.pos); t.threads.forEach(th=>collect(th.pos)); });
  const rawOrigin=goodPos(data.map.origin), rawSpores=(data.map.ambientSpores||[]).map(goodPos).filter(Boolean);
  collect(rawOrigin); rawSpores.forEach(collect);
  let T=null;
  if(abs.length>=3){
    const pts=isPortrait?abs.map(p=>[p[1],p[0]]):abs;
    let minx=1/0,miny=1/0,maxx=-1/0,maxy=-1/0;
    pts.forEach(([x,y])=>{minx=Math.min(minx,x);miny=Math.min(miny,y);maxx=Math.max(maxx,x);maxy=Math.max(maxy,y);});
    const bw=Math.max(1,maxx-minx), bh=Math.max(1,maxy-miny);
    // room at the top for the header bar and at the bottom for the legend chips
    const availW=VB.w-2*VB.pad, availH=VB.h-2*VB.pad-(isPortrait?420:150);
    const s=Math.min(availW/bw, availH/bh);
    const ox=(VB.w-bw*s)/2 - minx*s, oy=(VB.h-bh*s)/2 - miny*s + (isPortrait?-40:0);
    T=(p)=>{ const q=isPortrait?[p[1],p[0]]:p; return {x:q[0]*s+ox, y:q[1]*s+oy}; };
  }
  const place=(p)=>{ if(!p)return null; if(isFrac(p)) return {x:p[0]*VB.w,y:p[1]*VB.h}; return T?T(p):null; };
  const cx=VB.w/2, cy=VB.h/2;
  data.trunks.forEach((t,ti)=>{
    const authored=place(t.pos), a=ANCHORS[ti%ANCHORS.length];
    const tp=authored||{x:a[0]*VB.w,y:a[1]*VB.h};
    POS[t.id]=tp;
    const n=t.threads.length, base=Math.atan2(tp.y-cy,tp.x-cx), spread=Math.PI*(isPortrait?0.95:0.85);
    t.threads.forEach((th,i)=>{
      const ap=place(th.pos); if(ap){ POS[th.id]=ap; return; }
      const frac=n===1?0:(i/(n-1))-0.5, ang=base+frac*spread, rad=(isPortrait?215:165)+((i*53)%70);
      POS[th.id]={x:clamp(tp.x+Math.cos(ang)*rad,VB.pad,VB.w-VB.pad), y:clamp(tp.y+Math.sin(ang)*rad,VB.pad+30,VB.h-VB.pad)};
    });
  });
  ORIGIN=place(rawOrigin); SPORES=rawSpores.map(place).filter(Boolean);
}

